"""Chat list and turn history for the UI (conversation history panel).

LangGraph checkpoints hold the agent's memory; this small SQLite store holds what
the UI needs to list chats and redraw them: one row per thread (owner, title,
timestamps) and one row per turn (the full response, so a chat can be reopened
exactly as it was, and its SQL re-run for CSV export).

Threads belong to an anonymous client id generated by the browser — on a public
demo every visitor sees only their own chats, without accounts.
"""

from __future__ import annotations

import json
import sqlite3
import threading
from datetime import UTC, datetime
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS threads (
    thread_id   TEXT PRIMARY KEY,
    client_id   TEXT NOT NULL,
    title       TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    turns       INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_threads_client ON threads (client_id, updated_at);
CREATE TABLE IF NOT EXISTS turns (
    request_id  TEXT PRIMARY KEY,
    thread_id   TEXT NOT NULL REFERENCES threads (thread_id) ON DELETE CASCADE,
    question    TEXT NOT NULL,
    response    TEXT NOT NULL,
    created_at  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_turns_thread ON turns (thread_id, created_at);
"""


def _now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


class ThreadStore:
    def __init__(self, path: Path):
        path.parent.mkdir(parents=True, exist_ok=True)
        self._con = sqlite3.connect(path, check_same_thread=False)
        self._con.row_factory = sqlite3.Row
        self._con.execute("PRAGMA foreign_keys = ON")
        self._con.executescript(SCHEMA)
        self._lock = threading.Lock()

    def owner(self, thread_id: str) -> str | None:
        row = self._con.execute("SELECT client_id FROM threads WHERE thread_id = ?", (thread_id,)).fetchone()
        return row["client_id"] if row else None

    def add_turn(self, thread_id: str, client_id: str, question: str, response: dict) -> None:
        now = _now()
        with self._lock, self._con:
            self._con.execute(
                "INSERT INTO threads (thread_id, client_id, title, created_at, updated_at) VALUES (?, ?, ?, ?, ?) "
                "ON CONFLICT (thread_id) DO NOTHING",
                (thread_id, client_id, _title(question), now, now))
            self._con.execute(
                "INSERT OR REPLACE INTO turns (request_id, thread_id, question, response, created_at) "
                "VALUES (?, ?, ?, ?, ?)",
                (response["request_id"], thread_id, question, json.dumps(response, default=str), now))
            self._con.execute("UPDATE threads SET updated_at = ?, turns = turns + 1 WHERE thread_id = ?",
                              (now, thread_id))

    def list_threads(self, client_id: str, limit: int = 100) -> list[dict]:
        rows = self._con.execute(
            "SELECT thread_id, title, created_at, updated_at, turns FROM threads WHERE client_id = ? "
            "ORDER BY updated_at DESC LIMIT ?", (client_id, limit)).fetchall()
        return [dict(r) for r in rows]

    def get_turns(self, thread_id: str) -> list[dict]:
        rows = self._con.execute(
            "SELECT request_id, question, response, created_at FROM turns WHERE thread_id = ? ORDER BY created_at, "
            "rowid", (thread_id,)).fetchall()
        return [{"request_id": r["request_id"], "question": r["question"], "created_at": r["created_at"],
                 "response": json.loads(r["response"])} for r in rows]

    def get_turn(self, request_id: str) -> dict | None:
        row = self._con.execute(
            "SELECT t.request_id, t.thread_id, t.question, t.response, th.client_id FROM turns t "
            "JOIN threads th ON th.thread_id = t.thread_id WHERE t.request_id = ?", (request_id,)).fetchone()
        if not row:
            return None
        return {"request_id": row["request_id"], "thread_id": row["thread_id"], "client_id": row["client_id"],
                "question": row["question"], "response": json.loads(row["response"])}

    def list_runs(self, client_id: str, limit: int = 100) -> list[dict]:
        """Every turn this owner ran, newest first, across all their chats (dev run history)."""
        rows = self._con.execute(
            "SELECT t.request_id, t.thread_id, th.title, t.question, t.response, t.created_at FROM turns t "
            "JOIN threads th ON th.thread_id = t.thread_id WHERE th.client_id = ? "
            "ORDER BY t.created_at DESC, t.rowid DESC LIMIT ?", (client_id, limit)).fetchall()
        return [{"request_id": r["request_id"], "thread_id": r["thread_id"], "thread_title": r["title"],
                 "question": r["question"], "created_at": r["created_at"], "response": json.loads(r["response"])}
                for r in rows]

    def rename(self, thread_id: str, title: str) -> None:
        with self._lock, self._con:
            self._con.execute("UPDATE threads SET title = ? WHERE thread_id = ?", (_title(title), thread_id))

    def delete(self, thread_id: str) -> None:
        with self._lock, self._con:
            self._con.execute("DELETE FROM turns WHERE thread_id = ?", (thread_id,))
            self._con.execute("DELETE FROM threads WHERE thread_id = ?", (thread_id,))


def _title(text: str) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= 60 else text[:57].rstrip() + "…"

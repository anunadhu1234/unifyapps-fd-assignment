"""Generate the reference docs from the code, so they can never drift from the implementation.

    docs/prompts.md    every prompt in prompt_library: node, version, model tier, output contract, full text
    docs/database.md   the sample database: ER diagram, every table/column with meaning and values,
                       relationships, business metrics, glossary and conventions (from the knowledge base)
    docs/workflow.md   the "Compiled graph" block is replaced with the mermaid LangGraph draws from the
                       compiled StateGraph (the rest of that file is hand-written)

Usage (from backend/):  python scripts/generate_docs.py
"""

from __future__ import annotations

import re
import sys

from langgraph.checkpoint.memory import InMemorySaver

from agent.knowledge.kb_resolver import get_kb
from agent.llm_client import STEP_TIERS
from agent.supervisor.dependencies import build_deps
from agent.supervisor.supervisor import build_graph
from prompt_library import REGISTRY, _shared
from utils.config import REPO_DIR

DOCS = REPO_DIR / "docs"
GENERATED = "<!-- Generated by backend/scripts/generate_docs.py — do not edit by hand. -->"

OUTPUT_CONTRACT = {
    "intent_detection": "`IntentResult` (structured output)",
    "query_planner": "`QueryPlan` (structured output)",
    "sql_generation": "`SQLDraft` (structured output)",
    "sql_repair": "`SQLDraft` (structured output)",
    "sql_optimization": "`OptimizationResult` (structured output)",
    "sql_debugging": "`DebugResult` (structured output)",
    "suggest_follow_ups": "`FollowUpSuggestions` (structured output)",
    "generate_explanation": "Markdown text, streamed token by token",
    "schema_answer": "Markdown text, streamed token by token",
}

PURPOSE = {
    "intent_detection": "Classify the request (generate / follow-up / optimize / debug / explain / schema question / "
                        "destructive / out of scope) and rewrite follow-ups into a standalone question.",
    "query_planner": "Turn the request into a structured plan (tables, columns, filters, grouping, ordering) — no SQL "
                     "yet — so every part can be grounded against the real schema first.",
    "sql_generation": "Write one read-only SQLite query that implements the grounded plan exactly.",
    "sql_repair": "Fix SQL that failed validation, using the validator's findings and fix hints verbatim.",
    "sql_optimization": "Rewrite a user's query for readability and speed, and recommend indexes (the rewrite is only "
                        "accepted if it returns exactly the same rows).",
    "sql_debugging": "Identify what is wrong with a user's query, explain why, and return a corrected version.",
    "generate_explanation": "Explain the final SQL in plain English for a business user.",
    "suggest_follow_ups": "Propose three grounded 'Dive deeper' follow-ups: a drill-down, a refinement, "
                          "a related question.",
    "schema_answer": "Answer questions about the database (or SQL concepts) from the knowledge-base "
                     "documentation only.",
}


def fence(text: str, lang: str = "text") -> str:
    return f"```{lang}\n{text.rstrip()}\n```"


def prompts_doc() -> str:
    out = [
        "# Prompts", "", GENERATED, "",
        "Every LLM call in the agent uses one of the prompts below. Each prompt lives in its own module in "
        "[`backend/prompt_library/`](../backend/prompt_library) named after the LangGraph node that uses it, and is "
        "built by `get_prompt(name, **vars)`. The prompt library owns only the prompt *text*; model choice, calling, "
        "parsing and retries belong to the nodes and the LLM gateway.", "",
        "## Design principles", "",
        "- **One prompt per node, structured output.** Every non-prose step is bound to a Pydantic schema through "
        "Bedrock JSON-schema output ([`agent/llm_schemas.py`](../backend/agent/llm_schemas.py)), with one tool-calling "
        "retry, so a malformed answer fails "
        "loudly instead of being parsed by regex.",
        "- **Ground before generating.** The planner never writes SQL; the SQL writer receives a plan whose names and "
        "values were already checked against the real schema and data.",
        "- **The validator is the source of truth.** The repair and debug prompts receive the deterministic "
        "validator's findings (code, message, fix hint) verbatim.",
        "- **User text is untrusted data.** It is always wrapped in `<user_input>` tags and every prompt carries the "
        "security rules below (prompt-injection defence layer 2 of 4).",
        "- **Placeholders** in `{braces}` are filled at runtime: the schema context comes from the knowledge graph, "
        "the plan from `plan_grounding`, the history from conversation memory.", "",
        "## Shared blocks", "",
        "### Security rules (included in every prompt)", "", fence(_shared.SECURITY_RULES), "",
        "### SQLite rules (included in every SQL-writing prompt)", "", fence(_shared.SQLITE_RULES), "",
        "## Prompt index", "",
        "| Prompt / node | Version | Model tier | Output | Purpose |",
        "|---|---|---|---|---|",
    ]
    for name, module in REGISTRY.items():
        tier = STEP_TIERS.get(name, "main")
        tier_text = "by plan complexity (fast ≤ 1, else main)" if tier == "auto" else tier
        out.append(f"| [`{name}`](#{name}) | {module.VERSION} | {tier_text} | "
                   f"{OUTPUT_CONTRACT.get(name, '')} | {PURPOSE.get(name, '')} |")
    for name, module in REGISTRY.items():
        out += ["", f"## {name}", "",
                f"**File:** [`backend/prompt_library/{name}.py`](../backend/prompt_library/{name}.py) · "
                f"**Version:** {module.VERSION} · **Output:** {OUTPUT_CONTRACT.get(name, '')}", "",
                PURPOSE.get(name, ""), "", "### System message", "", fence(module.SYSTEM), "",
                "### User message template", "", fence(module.USER)]
        if getattr(module, "MODE_RULES", None):
            out += ["", "### Mode-specific rules", ""]
            out += [f"- **{mode}:** {rule}" for mode, rule in module.MODE_RULES.items() if rule]
    return "\n".join(out) + "\n"


def database_doc() -> str:
    kb = get_kb()
    meta = kb.meta
    out = ["# Sample database", "", GENERATED, "",
           f"{meta['domain']}", "",
           f"- **Engine:** SQLite (`backend/data/company.db`) · **Snapshot date:** {meta['as_of_date']} · "
           f"**DDL:** [`backend/data/schema.sql`](../backend/data/schema.sql)",
           "- **Generated by:** [`backend/scripts/generate_data.py`](../backend/scripts/generate_data.py) "
           "(deterministic, fixed seed) · **Excel copy:** `backend/data/company_sample.xlsx`",
           "- **Meaning of every column** comes from "
           "[`backend/knowledge_base/semantic_layer.yaml`](../backend/knowledge_base/semantic_layer.yaml); "
           "statistics and values are profiled from the live database.", "",
           "## Entity–relationship diagram", "", "```mermaid", "erDiagram"]
    for r in kb.relationships:
        card = "}o--o|" if r["nullable"] else "}o--||"
        out.append(f'    {r["from_table"]} {card} {r["to_table"]} : "{r["from_column"]}"')
    for t, info in kb.tables.items():
        out.append(f"    {t} {{")
        for c, col in info["columns"].items():
            key = " PK" if col["role"] == "primary_key" else " FK" if col["role"] == "foreign_key" else ""
            out.append(f"        {col['type'].lower()} {c}{key}")
        out.append("    }")
    out += ["```", "", "## Tables", ""]
    out += ["| Table | Rows | Grain | Description |", "|---|---:|---|---|"]
    out += [f"| [{t}](#{t.lower()}) | {i['row_count']:,} | {i['grain']} | {i['description']} |"
            for t, i in kb.tables.items()]
    for t, info in kb.tables.items():
        out += ["", f"### {t}", "", info["description"], "",
                "| Column | Type | Key | Description | Values / range |", "|---|---|---|---|---|"]
        for c, col in info["columns"].items():
            key = "PK" if col["role"] == "primary_key" else f"FK → {col['references']}" if col.get("references") else ""
            out.append(f"| `{c}` | {col['type']} | {key} | {col['description'].replace('|', '/')} | {_values(col)} |")
        idx = [f"`{i['name']}` ({', '.join(i['columns'])})" for i in info["indexes"] if i["origin"] == "CREATE INDEX"]
        if idx:
            out += ["", f"Indexes: {', '.join(idx)}"]
    out += ["", "## Relationships", "", "| Join | Meaning |", "|---|---|"]
    out += [f"| `{r['join_condition']}` | {r['description']} |" for r in kb.relationships]
    out += ["", "Customers ↔ Employees can be linked two ways — the customer's **account manager** "
            "(`Customers.AccountManagerID`) or the **sales rep who booked an order** (`Orders.EmployeeID`). The "
            "knowledge graph flags this ambiguity and the planner states which link it chose."]
    out += ["", "## Business metrics", "", "Validated definitions the agent reuses (each one was executed against "
            "the database when the knowledge base was built).", "",
            "| Metric | Definition | Value at snapshot |", "|---|---|---:|"]
    for m in kb.metrics.values():
        definition = m.get("expression") or m["sql"]
        if m.get("default_filters"):
            definition += " WHERE " + " AND ".join(m["default_filters"])
        out.append(f"| **{m['name']}** — {m['description']} | `{definition}` | {m['value_at_snapshot']:,} |")
    out += ["", "## Business glossary", "", "| Term | Definition | SQL condition |", "|---|---|---|"]
    for g in kb.glossary.values():
        sql = f"`{g['sql']}`" if g.get("sql") else (f"default: {g.get('default')}" if g.get("ambiguous") else "")
        out.append(f"| {g['term']} | {g['definition']} | {sql} |")
    out += ["", "## Conventions the agent follows", ""]
    out += [f"- {c['rule']}" for c in kb.dictionary["conventions"]]
    return "\n".join(out) + "\n"


def _values(col: dict) -> str:
    if col.get("semantic_type") == "us_state":
        return "2-letter USPS state codes"
    if col.get("values") and len(col["values"]) <= 12:
        return ", ".join(f"`{v['value']}`" for v in col["values"])
    if col.get("values"):
        return f"{len(col['values'])} distinct values"
    stats = col.get("stats", {})
    if stats.get("min") is not None and col["role"] in ("date", "measure"):
        return f"{stats['min']} – {stats['max']}"
    return ""


def workflow_graph() -> str:
    graph = build_graph(build_deps(), InMemorySaver()).get_graph()
    mermaid = graph.draw_mermaid()
    mermaid = re.sub(r"^---\n.*?\n---\n", "", mermaid, flags=re.S)  # drop the front-matter block
    return "```mermaid\n" + mermaid.strip() + "\n```"


def main() -> int:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "prompts.md").write_text(prompts_doc(), encoding="utf-8")
    (DOCS / "database.md").write_text(database_doc(), encoding="utf-8")
    workflow = DOCS / "workflow.md"
    if workflow.exists():
        text = workflow.read_text(encoding="utf-8")
        block = f"<!-- graph:start -->\n{GENERATED}\n\n{workflow_graph()}\n<!-- graph:end -->"
        text = re.sub(r"<!-- graph:start -->.*?<!-- graph:end -->", lambda _: block, text, flags=re.S)
        workflow.write_text(text, encoding="utf-8")
    print("docs generated: prompts.md, database.md" + (", workflow.md graph" if workflow.exists() else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
